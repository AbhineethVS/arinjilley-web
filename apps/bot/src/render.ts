// Renders posters to PNG with Cloudflare Browser Rendering (a headless Chrome).
// Rendering in the Worker itself is too CPU-heavy for the free plan (error 1102), but browser time doesn't
// count as Worker CPU. Free plan: 10 browser-minutes/day, 3 concurrent browsers, 1 new browser per 20 s.
//
// Budget: the browser is closed as soon as the poster is taken (an idle open browser still uses up the daily
// minutes), and fonts are inlined so nothing is downloaded. A poster costs roughly 3–5 browser-seconds.

import { POSTER_HEIGHT, POSTER_WIDTH, type PosterData, posterHtml } from "@arinjilley/core/poster";
import puppeteer from "@cloudflare/puppeteer";
// Generated by scripts/fetch-fonts.mjs (base64 @font-face rules for General Sans + JetBrains Mono).
import POSTER_FONTS_CSS from "../../../packages/core/assets/fonts/fontshare/poster-fonts.txt";

export class RenderBusyError extends Error {
  constructor(public retryAfterMs: number) {
    super(`Browser Rendering is busy; try again in ${Math.ceil(retryAfterMs / 1000)}s`);
  }
}

/** Waits for the free plan's "1 new browser per 20 s" allowance if needed (up to `maxWaitMs`), then launches. */
async function launch(env: Env, maxWaitMs: number) {
  const limits = await puppeteer.limits(env.BROWSER);
  if (limits.allowedBrowserAcquisitions < 1) {
    const wait = limits.timeUntilNextAllowedBrowserAcquisition + 500;
    if (wait > maxWaitMs) throw new RenderBusyError(limits.timeUntilNextAllowedBrowserAcquisition);
    await new Promise((r) => setTimeout(r, wait));
  }
  return puppeteer.launch(env.BROWSER);
}

export async function renderPosterPng(env: Env, data: PosterData): Promise<Uint8Array> {
  const started = Date.now();
  const browser = await launch(env, 20_000);
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: POSTER_WIDTH, height: POSTER_HEIGHT, deviceScaleFactor: 1 });
    await page.setContent(posterHtml(data, POSTER_FONTS_CSS), { waitUntil: "load", timeout: 15_000 });
    // Runs inside the browser page (string form, since the Worker has no DOM types).
    await page.evaluate("document.fonts.ready.then(() => true)");
    const png = await page.screenshot({
      type: "png",
      clip: { x: 0, y: 0, width: POSTER_WIDTH, height: POSTER_HEIGHT },
    });
    console.log(`poster rendered in ${Date.now() - started} ms`);
    return new Uint8Array(png);
  } finally {
    await browser.close().catch(() => {});
  }
}
