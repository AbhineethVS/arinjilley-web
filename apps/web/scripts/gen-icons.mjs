// Generates shared/icons.ts with just the Phosphor icons the site uses, as inline SVG paths.
// Run after changing the list: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const root = join(dirname(require.resolve("@phosphor-icons/core")), "..");

const REGULAR = [
  "alarm",
  "arrow-down",
  "arrow-left",
  "arrow-up-right",
  "buildings",
  "calendar-blank",
  "calendar-plus",
  "caret-double-right",
  "caret-down",
  "caret-up",
  "copy",
  "globe-simple",
  "graduation-cap",
  "hourglass-medium",
  "info",
  "magnifying-glass",
  "map-pin",
  "share-network",
  "ticket",
  "trophy",
  "users",
  "whatsapp-logo",
  "x",
];
const BOLD = ["caret-down", "check"];

const inner = (file) => {
  const svg = readFileSync(join(root, "assets", file), "utf8");
  return svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
};

const entries = [
  ...REGULAR.map((n) => [n, inner(`regular/${n}.svg`)]),
  ...BOLD.map((n) => [`${n}-bold`, inner(`bold/${n}-bold.svg`)]),
];

const out = `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT). Do not edit by hand.
export const ICONS: Record<string, string> = {
${entries.map(([n, body]) => `  ${JSON.stringify(n)}: ${JSON.stringify(body)},`).join("\n")}
};
`;
writeFileSync(join(here, "../shared/icons.ts"), out);
console.log(`icons: wrote ${entries.length} icons`);
